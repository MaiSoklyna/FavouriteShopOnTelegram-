-- 041: Merchant setup wizard
--
-- A shop is visible to customers once it is active AND its setup is complete
-- (merchants.setup_completed_at). The backend sets that timestamp by itself when every required
-- item is done (name, shop type, logo, address + map pin, opening hours, Telegram order group,
-- a category, a product, delivery settings), or the platform admin publishes the shop by hand.
-- The checklist itself is not stored: it is worked out from the shop's data.
--
--   merchants.setup_completed_at   when the shop went live (NULL = still setting up, hidden)
--   merchants.delivery_fee_mode    'platform' (standard fee bands) | 'custom' (own base + per km);
--                                  NULL = the owner has not chosen yet
--   category_templates             starter categories suggested per shop type / subtype
--
-- Existing active shops stay visible (decision 2026-11-25): they are marked live now, and their
-- missing items show on their dashboards as tasks. Safe to run more than once. The backend keeps
-- working before this is run (every active shop counts as visible, as today).

ALTER TABLE merchants ADD COLUMN IF NOT EXISTS setup_completed_at timestamptz;
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS delivery_fee_mode text;
ALTER TABLE merchants DROP CONSTRAINT IF EXISTS merchants_delivery_fee_mode_check;
ALTER TABLE merchants ADD CONSTRAINT merchants_delivery_fee_mode_check
  CHECK (delivery_fee_mode IS NULL OR delivery_fee_mode IN ('platform', 'custom'));

CREATE INDEX IF NOT EXISTS idx_merchants_status_live ON merchants (status, setup_completed_at);

-- Keep today's shops visible (only the first time: a shop set up later keeps its own timestamp)
UPDATE merchants SET setup_completed_at = COALESCE(created_at, now())
 WHERE status = 'active' AND setup_completed_at IS NULL
   AND NOT EXISTS (SELECT 1 FROM merchants m2 WHERE m2.setup_completed_at IS NOT NULL);

-- ── Starter categories ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS category_templates (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_category_id    int  NOT NULL REFERENCES shop_categories(id),
  shop_subcategory_id int  REFERENCES shop_subcategories(id),   -- NULL = for every subtype of the type
  name                text NOT NULL,
  name_kh             text,
  icon_emoji          text,
  sort_order          int  NOT NULL DEFAULT 0,
  is_active           boolean NOT NULL DEFAULT true,
  created_at          timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_category_templates
  ON category_templates (shop_category_id, COALESCE(shop_subcategory_id, 0), lower(name));
ALTER TABLE category_templates ENABLE ROW LEVEL SECURITY;

-- Seed: platform configuration (suggestions a shop may pick), not demo content
CREATE OR REPLACE FUNCTION pg_temp.seed_cats(p_type text, p_subtype text, p_names text[], p_emojis text[])
RETURNS void LANGUAGE sql AS $$
  INSERT INTO category_templates (shop_category_id, shop_subcategory_id, name, icon_emoji, sort_order)
  SELECT sc.id,
         (SELECT ss.id FROM shop_subcategories ss WHERE ss.category_id = sc.id AND ss.name = p_subtype),
         n.name, p_emojis[n.ord], n.ord
    FROM shop_categories sc, unnest(p_names) WITH ORDINALITY AS n(name, ord)
   WHERE sc.name = p_type
     AND (p_subtype IS NULL OR EXISTS (SELECT 1 FROM shop_subcategories ss WHERE ss.category_id = sc.id AND ss.name = p_subtype))
  ON CONFLICT DO NOTHING;
$$;

