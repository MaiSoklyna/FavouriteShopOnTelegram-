-- 036: Product attribute templates
--
-- The platform defines, per shop type, templates of structured product details ("Skin type",
-- "Storage", "Serves"); shops fill the values for their products. Values live on the product in
-- one JSON column, validated by the backend against the product's template.
--
--   attribute_templates     "Skincare" under Health & Beauty (suggested for shops of the listed subtypes)
--   attribute_definitions   one field: key, label, type, unit, options, filterable, importance
--   products.attribute_template_id / products.attributes
--
-- importance: 'recommended' fields count double in the product form's completeness score;
--             'optional' fields count once. No field is required (decision 2026-11-23).
-- The seeded templates are platform configuration, not demo content. Safe to run more than once.

CREATE TABLE IF NOT EXISTS attribute_templates (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key                  text NOT NULL UNIQUE,
  shop_category_id     int  NOT NULL REFERENCES shop_categories(id),
  shop_subcategory_ids int[] NOT NULL DEFAULT '{}',   -- shop subtypes this template is suggested for
  name                 text NOT NULL,
  name_kh              text,
  sort_order           int  NOT NULL DEFAULT 0,
  is_active            boolean NOT NULL DEFAULT true,
  created_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attribute_definitions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id  bigint NOT NULL REFERENCES attribute_templates(id) ON DELETE CASCADE,
  key          text NOT NULL CHECK (key ~ '^[a-z][a-z0-9_]{0,39}$'),
  label        text NOT NULL,
  label_kh     text,
  type         text NOT NULL CHECK (type IN ('text', 'number', 'select', 'multi_select', 'boolean')),
  unit         text,                                    -- number fields: ml, GB, cm, months, people
  options      jsonb NOT NULL DEFAULT '[]',             -- select fields: [{"value": "oily", "label": "Oily"}]
  filterable   boolean NOT NULL DEFAULT false,
  importance   text NOT NULL DEFAULT 'optional' CHECK (importance IN ('recommended', 'optional')),
  required     boolean NOT NULL DEFAULT false,          -- reserved: nothing is required yet
  help_text    text,
  min_value    numeric,
  max_value    numeric,
  sort_order   int NOT NULL DEFAULT 0,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (template_id, key)
);

CREATE INDEX IF NOT EXISTS idx_attribute_definitions_template ON attribute_definitions (template_id, sort_order);

ALTER TABLE products ADD COLUMN IF NOT EXISTS attribute_template_id bigint REFERENCES attribute_templates(id);
ALTER TABLE products ADD COLUMN IF NOT EXISTS attributes jsonb NOT NULL DEFAULT '{}';
CREATE INDEX IF NOT EXISTS idx_products_attributes ON products USING gin (attributes);
CREATE INDEX IF NOT EXISTS idx_products_attribute_template ON products (attribute_template_id);

ALTER TABLE attribute_templates   ENABLE ROW LEVEL SECURITY;
ALTER TABLE attribute_definitions ENABLE ROW LEVEL SECURITY;

-- ── Seed: 11 templates across the five shop types ───────────────

CREATE OR REPLACE FUNCTION pg_temp.seed_template(p_key text, p_shop_type text, p_subtypes text[], p_name text, p_sort int)
RETURNS void LANGUAGE sql AS $$
  INSERT INTO attribute_templates (key, shop_category_id, shop_subcategory_ids, name, sort_order)
  SELECT p_key, sc.id,
         COALESCE((SELECT array_agg(ss.id) FROM shop_subcategories ss WHERE ss.category_id = sc.id AND ss.name = ANY (p_subtypes)), '{}'),
         p_name, p_sort
  FROM shop_categories sc WHERE sc.name = p_shop_type
  ON CONFLICT (key) DO NOTHING;
$$;

-- options given as labels; values are the labels in snake_case ("Serum / Ampoule" -> "serum_ampoule")
CREATE OR REPLACE FUNCTION pg_temp.seed_field(p_template text, p_sort int, p_key text, p_label text, p_type text,
                                              p_unit text, p_options text[], p_filterable boolean, p_importance text,
                                              p_help text DEFAULT NULL)
RETURNS void LANGUAGE sql AS $$
  INSERT INTO attribute_definitions (template_id, key, label, type, unit, options, filterable, importance, help_text, sort_order)
  SELECT t.id, p_key, p_label, p_type, p_unit,
         COALESCE((SELECT jsonb_agg(jsonb_build_object(
                     'value', trim(both '_' from lower(regexp_replace(o, '[^A-Za-z0-9]+', '_', 'g'))),
                     'label', o) ORDER BY ord)
                   FROM unnest(p_options) WITH ORDINALITY AS u(o, ord)), '[]'::jsonb),
         p_filterable, p_importance, p_help, p_sort
  FROM attribute_templates t WHERE t.key = p_template
  ON CONFLICT (template_id, key) DO NOTHING;
$$;

