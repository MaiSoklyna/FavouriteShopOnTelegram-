-- 039: Refunds
--
-- When the platform collected a customer's money (KHQR or card) and the order does not go ahead, the
-- customer must get that money back. Until now the backend only wrote "refund required" to its log.
-- Now it records a refund to do:
--
--   order_cancelled           a paid order was cancelled (by the shop or the platform)
--   paid_after_cancellation   the payment arrived after the order had been cancelled
--   paid_after_expiry         the payment arrived after the order had expired (migration 038)
--
-- A platform admin sends the money back (bank transfer, ABA, or a refund in the Stripe dashboard) and
-- marks the refund done with the transfer's reference. The order's payment_status then becomes
-- 'refunded'. One refund per order, always for the full amount paid (partial refunds: future work).
--
-- The merchant's earning is not touched here: cancelling a paid order already reverses it
-- (reverse_order_earning), and a payment on a cancelled or expired order never records one.
--
-- Safe to run more than once. The backend keeps working before this is run (refunds are then only
-- written to the log, as before).

CREATE TABLE IF NOT EXISTS refunds (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id           bigint NOT NULL UNIQUE REFERENCES orders(id),
  merchant_id        bigint,                  -- copy, for filtering (no FK: kept if a shop is removed)
  user_id            bigint,                  -- the customer to pay back
  order_code         text,
  amount             numeric(12, 2) NOT NULL CHECK (amount > 0),
  currency           text NOT NULL DEFAULT 'USD',
  payment_method     text NOT NULL,           -- khqr | stripe
  payment_ref        text,                    -- PayWay transaction / Stripe PaymentIntent the money came from
  reason             text NOT NULL CHECK (reason IN ('order_cancelled', 'paid_after_cancellation', 'paid_after_expiry')),
  status             text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'refunded')),
  refund_reference   text,                    -- bank transfer / Stripe refund id, entered when done
  note               text,
  requested_by_type  text NOT NULL DEFAULT 'system',
  requested_by_id    text,
  completed_by_id    text,                    -- super_admins.id
  completed_by_name  text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  completed_at       timestamptz,
  CHECK ((status = 'refunded') = (completed_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_refunds_status_created ON refunds (status, created_at);
CREATE INDEX IF NOT EXISTS idx_refunds_merchant ON refunds (merchant_id);

ALTER TABLE refunds ENABLE ROW LEVEL SECURITY;   -- backend (service role) only
REVOKE ALL ON refunds FROM anon, authenticated;

-- orders.payment_status must accept 'refunded'. 001 created it as an enum that already has the value;
-- the live database stores text. Widen a CHECK constraint on it if there is one without 'refunded'.
DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT conname, pg_get_constraintdef(oid) AS def
      FROM pg_constraint
     WHERE conrelid = 'orders'::regclass AND contype = 'c'
       AND pg_get_constraintdef(oid) ~ 'payment_status'
       AND pg_get_constraintdef(oid) LIKE '%''paid''%'
       AND pg_get_constraintdef(oid) NOT LIKE '%''refunded''%'
  LOOP
    EXECUTE format('ALTER TABLE orders DROP CONSTRAINT %I', r.conname);
    EXECUTE format('ALTER TABLE orders ADD CONSTRAINT %I %s', r.conname,
                   regexp_replace(r.def, '''paid''(::[a-z_ ]+)?', '''paid''\1, ''refunded''\1'));
    RAISE NOTICE 'Widened % to allow refunded', r.conname;
  END LOOP;
END $$;

