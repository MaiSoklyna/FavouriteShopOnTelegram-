-- 034: Merchant staff accounts and the shop activity log
--
-- 1. merchant_admins.role is now 'owner' or 'staff'. The old default 'admin' meant owner.
-- 2. merchant_audit_log: who changed what in a shop, and when. Append-only.
--
-- Safe to run more than once. The app keeps working before this is run
-- (staff cannot be added and the activity log is skipped).

-- ── 1. Shop roles ───────────────────────────────────────────────

UPDATE merchant_admins SET role = 'owner' WHERE role IS NULL OR role NOT IN ('owner', 'staff');

ALTER TABLE merchant_admins ALTER COLUMN role SET DEFAULT 'owner';
ALTER TABLE merchant_admins ALTER COLUMN role SET NOT NULL;

ALTER TABLE merchant_admins DROP CONSTRAINT IF EXISTS merchant_admins_role_check;
ALTER TABLE merchant_admins ADD CONSTRAINT merchant_admins_role_check CHECK (role IN ('owner', 'staff'));

-- One Telegram account signs in to one shop account
CREATE UNIQUE INDEX IF NOT EXISTS uq_merchant_admins_telegram_id
  ON merchant_admins (telegram_id) WHERE telegram_id IS NOT NULL;

-- ── 2. Activity log ─────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS merchant_audit_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id   int  NOT NULL REFERENCES merchants(id) ON DELETE CASCADE,
  actor_type    text NOT NULL CHECK (actor_type IN ('owner', 'staff', 'super_admin', 'system', 'user')),
  actor_id      text,               -- merchant_admins.id / super_admins.id (no FK: the person may be removed)
  actor_name    text,               -- copy of the name at the time
  action        text NOT NULL,      -- e.g. 'product.price_changed', 'order.accepted'
  target_type   text NOT NULL,      -- 'product' | 'order' | 'driver' | 'promotion' | 'coupon' | 'shop' | 'payout' | 'staff'
  target_id     bigint,
  target_label  text,               -- copy of the target's name ("Matcha Cake", "FS-261023-9367")
  old_value     jsonb,              -- only the fields that changed
  new_value     jsonb,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_merchant_audit_shop_time   ON merchant_audit_log (merchant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_merchant_audit_shop_action ON merchant_audit_log (merchant_id, action);
CREATE INDEX IF NOT EXISTS idx_merchant_audit_shop_actor  ON merchant_audit_log (merchant_id, actor_id);

-- Append-only: nobody edits or deletes history (removing a shop still cascades)
CREATE OR REPLACE FUNCTION merchant_audit_log_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'merchant_audit_log is append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_merchant_audit_log_immutable ON merchant_audit_log;
CREATE TRIGGER trg_merchant_audit_log_immutable
  BEFORE UPDATE ON merchant_audit_log
  FOR EACH ROW EXECUTE FUNCTION merchant_audit_log_immutable();

DROP TRIGGER IF EXISTS trg_merchant_audit_log_no_delete ON merchant_audit_log;
CREATE TRIGGER trg_merchant_audit_log_no_delete
  BEFORE DELETE ON merchant_audit_log
  FOR EACH ROW WHEN (pg_trigger_depth() = 0)
  EXECUTE FUNCTION merchant_audit_log_immutable();

-- Only the backend (service role) reads and writes it
ALTER TABLE merchant_audit_log ENABLE ROW LEVEL SECURITY;
