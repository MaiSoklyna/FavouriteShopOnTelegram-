-- 035: Merchant collections
--
-- A shop groups its own products into curated, ordered lists ("Birthday Cakes", "Christmas Gifts")
-- shown on its shop page. A product can be in several collections.
--
-- type: 'manual' = the shop picks the products (built now).
--       'smart'  = filled by a rule (reserved for future work; the API refuses to create one).
--
-- Customers see a collection only when it is active, inside its optional date range, and has at
-- least one active product. Safe to run more than once.

CREATE TABLE IF NOT EXISTS merchant_collections (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id  int  NOT NULL REFERENCES merchants(id) ON DELETE CASCADE,
  type         text NOT NULL DEFAULT 'manual' CHECK (type IN ('manual', 'smart')),
  title        text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 80),
  description  text CHECK (description IS NULL OR char_length(description) <= 300),
  cover_url    text,
  rules        jsonb,              -- smart collections only (future): the rule that picks products
  sort_order   int  NOT NULL DEFAULT 0,
  is_active    boolean NOT NULL DEFAULT true,
  starts_at    timestamptz,
  ends_at      timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT merchant_collections_dates CHECK (starts_at IS NULL OR ends_at IS NULL OR starts_at < ends_at)
);

CREATE INDEX IF NOT EXISTS idx_merchant_collections_shop ON merchant_collections (merchant_id, sort_order, id);

CREATE TABLE IF NOT EXISTS merchant_collection_products (
  collection_id  bigint NOT NULL REFERENCES merchant_collections(id) ON DELETE CASCADE,
  product_id     int    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  sort_order     int    NOT NULL DEFAULT 0,
  added_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (collection_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_merchant_collection_products_product ON merchant_collection_products (product_id);

-- A collection holds only its own shop's products (enforced here as well as in the API)
CREATE OR REPLACE FUNCTION merchant_collection_product_same_shop() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM merchant_collections c
    JOIN products p ON p.id = NEW.product_id
    WHERE c.id = NEW.collection_id AND p.merchant_id = c.merchant_id
  ) THEN
    RAISE EXCEPTION 'A collection can only contain its own shop''s products' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_merchant_collection_product_same_shop ON merchant_collection_products;
CREATE TRIGGER trg_merchant_collection_product_same_shop
  BEFORE INSERT OR UPDATE ON merchant_collection_products
  FOR EACH ROW EXECUTE FUNCTION merchant_collection_product_same_shop();

-- Only the backend (service role) reads and writes them
ALTER TABLE merchant_collections ENABLE ROW LEVEL SECURITY;
ALTER TABLE merchant_collection_products ENABLE ROW LEVEL SECURITY;
