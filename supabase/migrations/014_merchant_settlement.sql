-- ════════════════════════════════════════════════════════════════
-- 014 — Merchant settlement ledger
--
-- Records what the platform owes each merchant for orders it collected
-- money on (PayWay QR), the commission it keeps, and how/when merchants
-- are paid out. Works today with manual bank transfers; the same tables
-- carry ABA PayWay Split & Payout later (settlement_method = 'aba_split').
--
-- Requires 013_payway_payments.sql. Safe to re-run.
-- ════════════════════════════════════════════════════════════════

BEGIN;

-- ── 1. Merchant payout settings ─────────────────────────────────

ALTER TABLE merchants ADD COLUMN IF NOT EXISTS aba_account text;            -- added in 013
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS aba_account_name text;
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS payout_enabled boolean NOT NULL DEFAULT false;
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS payout_verification_status text NOT NULL DEFAULT 'unverified';
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS payout_verified_at timestamptz;
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS payout_verified_by text;
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS payout_rejection_reason text;
-- Per-merchant commission override (percent). NULL = platform default.
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS commission_rate numeric(5,2);

DO $$ BEGIN
  ALTER TABLE merchants ADD CONSTRAINT merchants_payout_verification_status_chk
    CHECK (payout_verification_status IN ('unverified', 'pending', 'verified', 'rejected'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  ALTER TABLE merchants ADD CONSTRAINT merchants_commission_rate_chk
    CHECK (commission_rate IS NULL OR (commission_rate >= 0 AND commission_rate <= 100));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ── 2. Order snapshots ──────────────────────────────────────────
-- Commission rate frozen at order time so a later rate change never
-- alters what was promised on an existing order.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS commission_rate numeric(5,2);
-- How the latest PayWay QR routes money: 'platform' (we collect) or
-- 'aba_split' (ABA pays the seller's share directly).
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payout_mode text NOT NULL DEFAULT 'platform';

DO $$ BEGIN
  ALTER TABLE orders ADD CONSTRAINT orders_payout_mode_chk
    CHECK (payout_mode IN ('platform', 'aba_split'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ── 3. Payouts (one transfer to one merchant) ───────────────────

CREATE TABLE IF NOT EXISTS merchant_payouts (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id        bigint NOT NULL REFERENCES merchants(id),
  currency           text NOT NULL DEFAULT 'USD',
  amount             numeric(12,2) NOT NULL CHECK (amount > 0),
  item_count         integer NOT NULL DEFAULT 0,
  -- 'manual_transfer' today; 'aba_payway_payout' once ABA enables Split & Payout
  method             text NOT NULL DEFAULT 'manual_transfer'
                       CHECK (method IN ('manual_transfer', 'aba_payway_payout')),
  status             text NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'processing', 'paid', 'failed', 'cancelled')),
  -- Destination snapshot: what the money was actually sent to
  aba_account        text,
  aba_account_name   text,
  -- Bank / PayWay reference proving the transfer
  reference          text,
  note               text,
  failure_reason     text,
  created_by         text,
  completed_by       text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  paid_at            timestamptz,
  failed_at          timestamptz
);

CREATE INDEX IF NOT EXISTS idx_merchant_payouts_merchant ON merchant_payouts (merchant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_merchant_payouts_status ON merchant_payouts (status);

-- ── 4. Earnings ledger (what each order earns the merchant) ─────

CREATE TABLE IF NOT EXISTS merchant_earnings (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id        bigint NOT NULL REFERENCES merchants(id),
  order_id           bigint REFERENCES orders(id),
  -- 'order' = sale; 'adjustment' = correction (e.g. refund after payout, negative)
  entry_type         text NOT NULL DEFAULT 'order' CHECK (entry_type IN ('order', 'adjustment')),
  currency           text NOT NULL DEFAULT 'USD',
  gross_amount       numeric(12,2) NOT NULL,   -- what the customer paid for this order
  commission_base    numeric(12,2) NOT NULL,   -- part of gross commission applies to
  commission_rate    numeric(5,2)  NOT NULL,   -- percent
  commission_amount  numeric(12,2) NOT NULL,   -- platform revenue
  net_amount         numeric(12,2) NOT NULL,   -- owed to merchant (gross - commission)
  -- 'platform' = platform received the money; 'merchant' = merchant did (e.g. COD)
  collected_by       text NOT NULL DEFAULT 'platform' CHECK (collected_by IN ('platform', 'merchant')),
  -- 'manual' = settled by merchant_payouts; 'aba_split' = ABA pays at payment time
  settlement_method  text NOT NULL DEFAULT 'manual' CHECK (settlement_method IN ('manual', 'aba_split')),
  status             text NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'ready', 'paid', 'failed', 'reversed')),
  payway_tran_id     text,
  -- Payout currently carrying this earning (NULL when not in a payout)
  payout_id          bigint REFERENCES merchant_payouts(id),
  description        text,
  ready_at           timestamptz,
  paid_at            timestamptz,
  reversed_at        timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT merchant_earnings_amounts_chk
    CHECK (net_amount = gross_amount - commission_amount)
);

-- At most one sale entry per order — makes earning creation idempotent
CREATE UNIQUE INDEX IF NOT EXISTS uq_merchant_earnings_order
  ON merchant_earnings (order_id) WHERE entry_type = 'order';
CREATE INDEX IF NOT EXISTS idx_merchant_earnings_merchant_status
  ON merchant_earnings (merchant_id, status);
CREATE INDEX IF NOT EXISTS idx_merchant_earnings_payout ON merchant_earnings (payout_id);

-- ── 5. Payout items (permanent record of what each payout covered) ─

CREATE TABLE IF NOT EXISTS merchant_payout_items (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payout_id    bigint NOT NULL REFERENCES merchant_payouts(id),
  earning_id   bigint NOT NULL REFERENCES merchant_earnings(id),
  amount       numeric(12,2) NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (payout_id, earning_id)
);

-- ── 6. Audit trail (append-only) ────────────────────────────────

CREATE TABLE IF NOT EXISTS settlement_audit_log (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type  text NOT NULL,     -- 'merchant' | 'earning' | 'payout'
  entity_id    bigint NOT NULL,
  merchant_id  bigint,
  action       text NOT NULL,     -- e.g. 'earning.created', 'payout.paid'
  actor_type   text NOT NULL,     -- 'system' | 'super_admin' | 'merchant_admin' | 'payway'
  actor_id     text,
  old_value    jsonb,
  new_value    jsonb,
  note         text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_settlement_audit_entity ON settlement_audit_log (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_settlement_audit_merchant ON settlement_audit_log (merchant_id, created_at DESC);

CREATE OR REPLACE FUNCTION settlement_audit_log_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'settlement_audit_log is append-only';
END $$;

DROP TRIGGER IF EXISTS trg_settlement_audit_log_immutable ON settlement_audit_log;
CREATE TRIGGER trg_settlement_audit_log_immutable
  BEFORE UPDATE OR DELETE ON settlement_audit_log
  FOR EACH ROW EXECUTE FUNCTION settlement_audit_log_immutable();

-- updated_at maintenance
CREATE OR REPLACE FUNCTION settlement_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_merchant_earnings_touch ON merchant_earnings;
CREATE TRIGGER trg_merchant_earnings_touch BEFORE UPDATE ON merchant_earnings
  FOR EACH ROW EXECUTE FUNCTION settlement_touch_updated_at();

DROP TRIGGER IF EXISTS trg_merchant_payouts_touch ON merchant_payouts;
CREATE TRIGGER trg_merchant_payouts_touch BEFORE UPDATE ON merchant_payouts
  FOR EACH ROW EXECUTE FUNCTION settlement_touch_updated_at();

