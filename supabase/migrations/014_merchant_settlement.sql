-- ── record_order_earning: idempotent; returns the earning row ───
CREATE OR REPLACE FUNCTION record_order_earning(
  p_order_id          bigint,
  p_merchant_id       bigint,
  p_currency          text,
  p_gross_amount      numeric,
  p_commission_base   numeric,
  p_commission_rate   numeric,
  p_commission_amount numeric,
  p_net_amount        numeric,
  p_collected_by      text,
  p_settlement_method text,
  p_payway_tran_id    text,
  p_actor_type        text,
  p_actor_id          text
) RETURNS merchant_earnings
LANGUAGE plpgsql AS $$
DECLARE
  v_row merchant_earnings;
BEGIN
  INSERT INTO merchant_earnings (
    merchant_id, order_id, entry_type, currency,
    gross_amount, commission_base, commission_rate, commission_amount, net_amount,
    collected_by, settlement_method, status, payway_tran_id
  ) VALUES (
    p_merchant_id, p_order_id, 'order', p_currency,
    p_gross_amount, p_commission_base, p_commission_rate, p_commission_amount, p_net_amount,
    p_collected_by, p_settlement_method, 'pending', p_payway_tran_id
  )
  ON CONFLICT (order_id) WHERE entry_type = 'order' DO NOTHING
  RETURNING * INTO v_row;

  IF v_row.id IS NULL THEN
    -- Already recorded (callback + poll race, retry, backfill)
    SELECT * INTO v_row FROM merchant_earnings
     WHERE order_id = p_order_id AND entry_type = 'order';
    RETURN v_row;
  END IF;

  INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, new_value)
  VALUES ('earning', v_row.id, v_row.merchant_id, 'earning.created', p_actor_type, p_actor_id, to_jsonb(v_row));

  RETURN v_row;
END $$;

-- ── mark_order_earning_ready: order delivered → earning payable ─
CREATE OR REPLACE FUNCTION mark_order_earning_ready(
  p_order_id   bigint,
  p_actor_type text,
  p_actor_id   text
) RETURNS merchant_earnings
LANGUAGE plpgsql AS $$
DECLARE
  v_row merchant_earnings;
BEGIN
  UPDATE merchant_earnings
     SET status = 'ready', ready_at = now()
   WHERE order_id = p_order_id AND entry_type = 'order' AND status = 'pending'
  RETURNING * INTO v_row;

  IF v_row.id IS NOT NULL THEN
    INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, old_value, new_value)
    VALUES ('earning', v_row.id, v_row.merchant_id, 'earning.ready', p_actor_type, p_actor_id,
            jsonb_build_object('status', 'pending'), jsonb_build_object('status', 'ready'));
  END IF;
  RETURN v_row;
END $$;

-- ── reverse_order_earning: order cancelled / refunded ───────────
-- Not yet paid  → earning reversed (merchant no longer owed it).
-- Already paid  → negative adjustment, deducted from the next payout.
-- In open payout → refused; fail or cancel that payout first.
CREATE OR REPLACE FUNCTION reverse_order_earning(
  p_order_id   bigint,
  p_reason     text,
  p_actor_type text,
  p_actor_id   text
) RETURNS merchant_earnings
LANGUAGE plpgsql AS $$
DECLARE
  v_row merchant_earnings;
  v_adj merchant_earnings;
BEGIN
  SELECT * INTO v_row FROM merchant_earnings
   WHERE order_id = p_order_id AND entry_type = 'order'
   FOR UPDATE;

  IF v_row.id IS NULL OR v_row.status = 'reversed' THEN
    RETURN v_row;
  END IF;

  IF v_row.payout_id IS NOT NULL AND v_row.status <> 'paid' THEN
    RAISE EXCEPTION 'Earning % is in open payout %; fail or cancel the payout first',
      v_row.id, v_row.payout_id USING ERRCODE = 'P0001';
  END IF;

  IF v_row.status = 'paid' THEN
    INSERT INTO merchant_earnings (
      merchant_id, order_id, entry_type, currency,
      gross_amount, commission_base, commission_rate, commission_amount, net_amount,
      collected_by, settlement_method, status, ready_at, description
    ) VALUES (
      v_row.merchant_id, v_row.order_id, 'adjustment', v_row.currency,
      -v_row.gross_amount, -v_row.commission_base, v_row.commission_rate,
      -v_row.commission_amount, -v_row.net_amount,
      v_row.collected_by, 'manual', 'ready', now(),
      'Reversal of paid earning #' || v_row.id || COALESCE(': ' || p_reason, '')
    ) RETURNING * INTO v_adj;

    INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, new_value, note)
    VALUES ('earning', v_adj.id, v_adj.merchant_id, 'earning.adjustment_created', p_actor_type, p_actor_id, to_jsonb(v_adj), p_reason);
    RETURN v_adj;
  END IF;

  UPDATE merchant_earnings
     SET status = 'reversed', reversed_at = now(),
         description = COALESCE(p_reason, description)
   WHERE id = v_row.id
  RETURNING * INTO v_adj;

  INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, old_value, new_value, note)
  VALUES ('earning', v_row.id, v_row.merchant_id, 'earning.reversed', p_actor_type, p_actor_id,
          jsonb_build_object('status', v_row.status), jsonb_build_object('status', 'reversed'), p_reason);
  RETURN v_adj;
END $$;

-- ── create_merchant_payout: bundle all available earnings ───────
CREATE OR REPLACE FUNCTION create_merchant_payout(
  p_merchant_id bigint,
  p_currency    text,
  p_method      text,
  p_note        text,
  p_actor_type  text,
  p_actor_id    text
) RETURNS merchant_payouts
LANGUAGE plpgsql AS $$
DECLARE
  v_merchant merchants;
  v_total    numeric(12,2);
  v_count    integer;
  v_payout   merchant_payouts;
BEGIN
  -- Serialise payout creation per merchant
  SELECT * INTO v_merchant FROM merchants WHERE id = p_merchant_id FOR UPDATE;
  IF v_merchant.id IS NULL THEN
    RAISE EXCEPTION 'Merchant % not found', p_merchant_id USING ERRCODE = 'P0002';
  END IF;

  PERFORM 1 FROM merchant_earnings
   WHERE merchant_id = p_merchant_id AND currency = p_currency
     AND status = 'ready' AND payout_id IS NULL AND settlement_method = 'manual'
   FOR UPDATE;

  SELECT COALESCE(SUM(net_amount), 0), COUNT(*) INTO v_total, v_count
    FROM merchant_earnings
   WHERE merchant_id = p_merchant_id AND currency = p_currency
     AND status = 'ready' AND payout_id IS NULL AND settlement_method = 'manual';

  IF v_count = 0 OR v_total <= 0 THEN
    RAISE EXCEPTION 'Nothing to pay out for merchant % (available %)', p_merchant_id, v_total
      USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO merchant_payouts (
    merchant_id, currency, amount, item_count, method, status,
    aba_account, aba_account_name, note, created_by
  ) VALUES (
    p_merchant_id, p_currency, v_total, v_count, p_method, 'pending',
    v_merchant.aba_account, v_merchant.aba_account_name, p_note, p_actor_id
  ) RETURNING * INTO v_payout;

  INSERT INTO merchant_payout_items (payout_id, earning_id, amount)
  SELECT v_payout.id, id, net_amount FROM merchant_earnings
   WHERE merchant_id = p_merchant_id AND currency = p_currency
     AND status = 'ready' AND payout_id IS NULL AND settlement_method = 'manual';

  UPDATE merchant_earnings SET payout_id = v_payout.id
   WHERE id IN (SELECT earning_id FROM merchant_payout_items WHERE payout_id = v_payout.id);

  INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, new_value, note)
  VALUES ('payout', v_payout.id, p_merchant_id, 'payout.created', p_actor_type, p_actor_id, to_jsonb(v_payout), p_note);

  RETURN v_payout;
END $$;

-- ── complete_merchant_payout: transfer confirmed ────────────────
CREATE OR REPLACE FUNCTION complete_merchant_payout(
  p_payout_id  bigint,
  p_reference  text,
  p_actor_type text,
  p_actor_id   text
) RETURNS merchant_payouts
LANGUAGE plpgsql AS $$
DECLARE
  v_payout merchant_payouts;
BEGIN
  SELECT * INTO v_payout FROM merchant_payouts WHERE id = p_payout_id FOR UPDATE;
  IF v_payout.id IS NULL THEN
    RAISE EXCEPTION 'Payout % not found', p_payout_id USING ERRCODE = 'P0002';
  END IF;
  IF v_payout.status NOT IN ('pending', 'processing') THEN
    RAISE EXCEPTION 'Payout % is %, cannot mark paid', p_payout_id, v_payout.status USING ERRCODE = 'P0001';
  END IF;
  IF COALESCE(trim(p_reference), '') = '' THEN
    RAISE EXCEPTION 'A transfer reference is required' USING ERRCODE = 'P0001';
  END IF;

  UPDATE merchant_payouts
     SET status = 'paid', reference = p_reference, paid_at = now(), completed_by = p_actor_id
   WHERE id = p_payout_id
  RETURNING * INTO v_payout;

  UPDATE merchant_earnings SET status = 'paid', paid_at = now()
   WHERE payout_id = p_payout_id;

  INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, new_value)
  VALUES ('payout', v_payout.id, v_payout.merchant_id, 'payout.paid', p_actor_type, p_actor_id,
          jsonb_build_object('status', 'paid', 'reference', p_reference, 'amount', v_payout.amount));
  RETURN v_payout;
END $$;

-- ── fail_merchant_payout: transfer failed / cancelled ───────────
-- Earnings are released back to 'ready' so they can be paid again;
-- merchant_payout_items keeps the history.
CREATE OR REPLACE FUNCTION fail_merchant_payout(
  p_payout_id  bigint,
  p_reason     text,
  p_cancel     boolean,
  p_actor_type text,
  p_actor_id   text
) RETURNS merchant_payouts
LANGUAGE plpgsql AS $$
DECLARE
  v_payout merchant_payouts;
  v_status text := CASE WHEN p_cancel THEN 'cancelled' ELSE 'failed' END;
BEGIN
  SELECT * INTO v_payout FROM merchant_payouts WHERE id = p_payout_id FOR UPDATE;
  IF v_payout.id IS NULL THEN
    RAISE EXCEPTION 'Payout % not found', p_payout_id USING ERRCODE = 'P0002';
  END IF;
  IF v_payout.status NOT IN ('pending', 'processing') THEN
    RAISE EXCEPTION 'Payout % is %, cannot mark %', p_payout_id, v_payout.status, v_status USING ERRCODE = 'P0001';
  END IF;

  UPDATE merchant_payouts
     SET status = v_status, failure_reason = p_reason, failed_at = now(), completed_by = p_actor_id
   WHERE id = p_payout_id
  RETURNING * INTO v_payout;

  UPDATE merchant_earnings SET payout_id = NULL
   WHERE payout_id = p_payout_id;

  INSERT INTO settlement_audit_log (entity_type, entity_id, merchant_id, action, actor_type, actor_id, new_value, note)
  VALUES ('payout', v_payout.id, v_payout.merchant_id, 'payout.' || v_status, p_actor_type, p_actor_id,
          jsonb_build_object('status', v_status), p_reason);
  RETURN v_payout;
END $$;

